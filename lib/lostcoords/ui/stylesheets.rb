require "fileutils"
require "pathname"

module Lostcoords::Ui
  # The Tailwind entries a host can import: the document defaults, core.css and one file per opt-in component.
  module Stylesheets
    ROOT = Pathname(File.expand_path("../../../app/assets/tailwind/lostcoords/ui", __dir__))

    def self.entries
      [ ROOT.join("base.css"), ROOT.join("core.css"), *ROOT.glob("components/*.css").sort ]
    end

    # tailwindcss-rails gives an engine one generated import, of engine.css. These proxies give every
    # entry a stable path in the host, such as builds/tailwind/lostcoords_ui/components/dialog.css.
    def self.write(builds)
      directory = Pathname(builds).join("lostcoords_ui")
      FileUtils.rm_rf(directory)
      entries.each do |entry|
        path = directory.join(entry.relative_path_from(ROOT))
        FileUtils.mkdir_p(path.dirname)
        path.write("/* Generated by lostcoords-ui before every Tailwind build; do not edit. */\n@import \"#{entry}\";\n")
      end
    end
  end
end
